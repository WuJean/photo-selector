import Foundation
import PhotoCore
import UIKit

/// Poster production for the tent presentation.
///
/// Every photograph is processed on its own: one artwork, one poster, one
/// file. Nothing is ever combined into a collage.
extension AppModel {
    /// True when an image-generation model is configured and ready.
    var imageModelReady: Bool {
        ImageGeneration.isConfigured(config: aiConfig, key: Keychain.loadImage())
    }

    /// The abstract artwork that belongs to one photograph.
    ///
    /// With a configured image model the artwork comes from that service and
    /// is derived from this photograph alone. Without one the artwork is
    /// rendered on device from the photograph's own colours, so the lower
    /// band of the poster always matches the upper photograph.
    func artwork(for asset: LocalAsset) async -> UIImage {
        await artwork(for: asset, photo: nil)
    }

    /// Same as `artwork(for:)` but reuses an already loaded photograph.
    func artwork(for asset: LocalAsset, photo supplied: UIImage?) async -> UIImage {
        if let cached = artworkCache[asset.id] { return cached }
        let photo: UIImage
        if let supplied {
            photo = supplied
        } else {
            photo = (try? await media.image(asset, maxSize: 1600, allowNetwork: allowCloudDownload)) ?? UIImage()
        }
        var result = LocalArtwork.make(from: photo)
        let config = aiConfig
        let key = Keychain.loadImage()
        if ImageGeneration.isConfigured(config: config, key: key) {
            do {
                let generated = try await imageGeneration.generate(prompt: ImageGeneration.posterPrompt(for: asset), reference: photo, size: config.imageSize, config: config, key: key)
                result = generated.image
            } catch {
                // The fallback stays honest: the poster is built, but it does
                // not pretend an image was generated by the model.
                notify("生图模型未生效，海报下半区改用本机抽象图：\(error.localizedDescription)", title: "已回退为本机抽象图")
            }
        }
        artworkCache[asset.id] = result
        return result
    }

    /// The editorial poster for one photograph: the Duo canvas split into two
    /// equal halves, photograph on top, artwork and typography underneath.
    func poster(for asset: LocalAsset, portfolio: Portfolio?, index: Int, total: Int) async -> UIImage {
        let cacheKey = "\(asset.id)-\(portfolio?.id ?? "")"
        if let cached = posterCache[cacheKey] { return cached }
        let photo = (try? await media.image(asset, maxSize: 2000, allowNetwork: allowCloudDownload)) ?? UIImage()
        let artwork = await artwork(for: asset)
        let meta = PosterMeta(
            series: "EDITORIAL POSTER",
            title: portfolio?.name ?? "未命名作品集",
            caption: asset.analysis?.description ?? asset.name,
            location: portfolio?.location ?? "",
            date: asset.takenAt ?? portfolio?.date ?? Date(),
            index: index,
            total: total
        )
        let image = PosterRenderer.render(photo: photo, artwork: artwork, meta: meta)
        posterCache[cacheKey] = image
        return image
    }

    /// Creates one independent poster per photograph in the portfolio and
    /// records each of them as a creation.
    func generatePosters(portfolioID: String) async {
        guard let portfolio = state.portfolios.first(where: { $0.id == portfolioID }) else { return }
        let assets = portfolio.assetIDs.compactMap { id in state.assets.first { $0.id == id } }
        guard !assets.isEmpty else { notify("这个作品集还没有照片。", title: "无法生成海报"); return }
        busy = true
        defer { busy = false; progress = "" }
        var created = 0
        for (offset, asset) in assets.enumerated() {
            progress = "生成海报 \(offset + 1)/\(assets.count)"
            let image = await poster(for: asset, portfolio: portfolio, index: offset + 1, total: assets.count)
            do {
                let relative = "posters/\(portfolio.id)/\(asset.id).jpg"
                let url = try media.url(relative)
                try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
                guard let data = image.jpegData(compressionQuality: 0.92) else { throw PhotoError.message("海报编码失败") }
                try data.write(to: url, options: .atomic)
                let creation = Creation(collectionID: portfolio.id, kind: "poster", title: "\(portfolio.name) · \(asset.name)", text: "\(PosterSpec.canvasSize.width) × \(PosterSpec.canvasSize.height) px · 上下各占一半", path: relative, sourceIDs: [asset.id])
                try change { s in
                    s.creations.removeAll { $0.kind == "poster" && $0.collectionID == portfolio.id && $0.sourceIDs == [asset.id] }
                    s.creations.append(creation)
                }
                created += 1
            } catch {
                self.error = "海报保存失败：\(error.localizedDescription)"
            }
        }
        notify("已为 \(created) 张照片各生成一张独立海报，没有做任何拼贴。", title: "海报已生成")
    }
}
